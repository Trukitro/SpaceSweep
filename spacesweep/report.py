"""Exportable report: one self-contained HTML page (to read or share) plus CSV files (for Excel).

Contents: drives, the Cleanup analysis of the system drive, what grew since the
previous disk scan, cache growth, and what the automatic tasks did. Paths
under your user folder are written as ~\\... so the report doesn't expose your
user name if you share it.
"""

import csv
import html
import os
import time

from . import __version__, automation, cleanup, history, winapi

HOME = os.path.expanduser("~")

TXT = {
    "es": {"title": "Reporte de espacio", "made": "Generado por SpaceSweep {v} el {d}", "drives": "Discos", "drive": "Disco",
           "free": "Libre", "used": "Usado", "total": "Total", "cleanup": "Limpieza en {d}", "item": "Qué", "group": "Grupo",
           "size": "Tamaño", "effect": "Qué pasa si lo borro", "grew": "Lo que más creció en {root} ({a} → {b})",
           "folder": "Carpeta", "before": "Antes", "after": "Ahora", "change": "Cambio", "caches": "Cachés que se vuelven a llenar",
           "auto": "Tareas automáticas", "when": "Cuándo", "what": "Qué", "none": "Sin datos.",
           "groups": {"safe": "Seguro", "review": "Decisión tuya", "space": "Se maneja en su app", "system": "Windows", "never": "No tocar"}},
    "en": {"title": "Disk space report", "made": "Generated by SpaceSweep {v} on {d}", "drives": "Drives", "drive": "Drive",
           "free": "Free", "used": "Used", "total": "Total", "cleanup": "Cleanup on {d}", "item": "What", "group": "Group",
           "size": "Size", "effect": "What happens if deleted", "grew": "What grew most in {root} ({a} → {b})",
           "folder": "Folder", "before": "Before", "after": "Now", "change": "Change", "caches": "Caches that keep refilling",
           "auto": "Automatic tasks", "when": "When", "what": "What", "none": "No data.",
           "groups": {"safe": "Safe", "review": "Your call", "space": "Managed in its app", "system": "Windows", "never": "Never touch"}},
}


def human(n):
    if n is None:
        return "—"
    n = float(n)
    for unit in ("B", "KB", "MB", "GB", "TB"):
        if abs(n) < 1024 or unit == "TB":
            return f"{n:.0f} {unit}" if unit == "B" else f"{n:.2f} {unit}"
        n /= 1024


def short(path):
    return "~" + path[len(HOME):] if path and path.lower().startswith(HOME.lower()) else path


def collect(job, drive=None):
    drive = drive or os.environ.get("SystemDrive", "C:") + "\\"
    job.update(message="drives")
    data = {"time": time.time(), "version": __version__, "drives": winapi.list_drives()}
    job.update(message="cleanup")
    data["cleanup"] = cleanup.scan(job, drive)
    data["growth"] = None
    # Prefer the drive's own history; otherwise the most recent folder that still exists.
    roots = [r for r in history.roots() if r["count"] > 1 and os.path.isdir(r["root"])]
    roots.sort(key=lambda r: (os.path.normcase(r["root"].rstrip("\\")) != os.path.normcase(drive.rstrip("\\")), -r["last_time"]))
    if roots:
        data["growth"] = history.compare(roots[0]["key"])
    data["caches"] = history.rule_growth(drive)
    data["auto"] = automation.read_log()[-20:][::-1]
    return data


def to_html(d, lang="es"):
    t = TXT.get(lang, TXT["es"])
    e = html.escape
    when = time.strftime("%Y-%m-%d %H:%M", time.localtime(d["time"]))
    rows = lambda cells: "<tr>" + "".join(f"<td>{c}</td>" for c in cells) + "</tr>"
    head = lambda cells: "<tr>" + "".join(f"<th>{e(c)}</th>" for c in cells) + "</tr>"
    out = [f"""<!doctype html><html lang="{lang}"><head><meta charset="utf-8"><title>{e(t['title'])}</title>
<style>body{{font:14px/1.5 "Segoe UI",system-ui,sans-serif;max-width:1000px;margin:24px auto;padding:0 16px;color:#17202b}}
h1{{margin:0}}.muted{{color:#5d6b7c}}table{{border-collapse:collapse;width:100%;margin:8px 0 24px}}th,td{{border-bottom:1px solid #e2e7ee;padding:6px 8px;text-align:left;vertical-align:top}}
th{{background:#f0f3f7;font-size:12px;text-transform:uppercase;color:#5d6b7c}}td.n{{text-align:right;white-space:nowrap}}.bar{{height:8px;background:#e6ebf1;border-radius:9px}}.bar i{{display:block;height:8px;background:#0d9488;border-radius:9px}}</style>
</head><body><h1>{e(t['title'])}</h1><p class="muted">{e(t['made'].format(v=d['version'], d=when))}</p>""",
           f"<h2>{e(t['drives'])}</h2><table>{head([t['drive'], t['free'], t['used'], t['total'], ''])}"]
    for dr in d["drives"]:
        pct = dr["used"] / dr["total"] * 100 if dr["total"] else 0
        out.append(rows([e(f"{dr['letter']}: {dr['label']}"), human(dr["free"]), human(dr["used"]), human(dr["total"]),
                         f'<div class="bar"><i style="width:{pct:.0f}%"></i></div>']))
    out.append("</table>")
    c = d["cleanup"]
    out.append(f"<h2>{e(t['cleanup'].format(d=c['drive']))}</h2><table>{head([t['item'], t['group'], t['size'], t['effect']])}")
    for i in c["items"]:
        out.append(rows([f"<b>{e(i['name'][lang])}</b><br><span class=muted>{e(i['what'][lang])}</span>", e(t["groups"][i["group"]]),
                         human(i["size"]) if i.get("measured") else "—", e(i["effect"][lang])]))
    out.append("</table>")
    g = d["growth"]
    if g and g.get("older"):
        a = time.strftime("%Y-%m-%d", time.localtime(g["older"]["time"]))
        b = time.strftime("%Y-%m-%d", time.localtime(g["newer"]["time"]))
        out.append(f"<h2>{e(t['grew'].format(root=short(g['root']), a=a, b=b))}</h2><table>{head([t['folder'], t['before'], t['after'], t['change']])}")
        for r in g["grew"][:30]:
            out.append(rows([e(short(r["full"])), human(r["before"]), human(r["after"]), "+" + human(r["delta"])]))
        out.append("</table>")
    if d["caches"]["items"]:
        names = {r["id"]: r["name"][lang] for r in cleanup.RULES}
        out.append(f"<h2>{e(t['caches'])}</h2><table>{head([t['item'], t['before'], t['after'], t['change']])}")
        for i in d["caches"]["items"]:
            out.append(rows([e(names.get(i["id"], i["id"])), human(i["before"]), human(i["after"]), "+" + human(i["delta"])]))
        out.append("</table>")
    if d["auto"]:
        out.append(f"<h2>{e(t['auto'])}</h2><table>{head([t['when'], t['what']])}")
        for a in d["auto"]:
            out.append(rows([time.strftime("%Y-%m-%d %H:%M", time.localtime(a["time"])), e(a["kind"])]))
        out.append("</table>")
    out.append("</body></html>")
    return "\n".join(out)


def to_csv(d, path, lang="es"):
    t = TXT.get(lang, TXT["es"])
    with open(path, "w", newline="", encoding="utf-8-sig") as fh:  # BOM so Excel opens accents correctly
        w = csv.writer(fh)
        w.writerow(["section", "name", "group", "bytes", "path"])
        for dr in d["drives"]:
            w.writerow(["drive", f"{dr['letter']}: {dr['label']}", "", dr["free"], dr["root"]])
        for i in d["cleanup"]["items"]:
            w.writerow(["cleanup", i["name"][lang], t["groups"][i["group"]], i["size"] if i.get("measured") else "",
                        short(i["paths"][0]["path"]) if i["paths"] else ""])
        g = d["growth"]
        if g and g.get("older"):
            for r in g["grew"]:
                w.writerow(["grew", "", "", r["delta"], short(r["full"])])


def export(job, folder=None, lang="es"):
    folder = folder or winapi.known_folder("documents")
    os.makedirs(folder, exist_ok=True)
    data = collect(job)
    stamp = time.strftime("%Y%m%d-%H%M", time.localtime(data["time"]))
    html_path = os.path.join(folder, f"SpaceSweep-report-{stamp}.html")
    csv_path = os.path.join(folder, f"SpaceSweep-report-{stamp}.csv")
    with open(html_path, "w", encoding="utf-8") as fh:
        fh.write(to_html(data, lang))
    to_csv(data, csv_path, lang)
    return {"html": html_path, "csv": csv_path}
